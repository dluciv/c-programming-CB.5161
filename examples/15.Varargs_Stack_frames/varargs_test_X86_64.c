/*
 * Manual parsing of variadic arguments on x86-64 (System V ABI).
 *
 * The key thing to understand: "..." does NOT put arguments on the stack.
 * The ellipsis only changes type-checking rules and default promotions
 * (char/short -> int, float -> double). Where the arguments physically live
 * is decided by the ABI, not by the ellipsis.
 *
 * System V AMD64 ABI (Linux, *BSD, macOS):
 *   integer arguments 1..6  -> rdi, rsi, rdx, rcx, r8, r9
 *   arguments 7 and later   -> stack, right after the return address (rbp+16, +24, ...)
 *   float/double 1..8       -> xmm0..xmm7 (al = how many were passed)
 *
 * So the naive attempt "arguments lie right after &f" yields garbage:
 * the compiler first stashes the incoming registers in its own stack frame,
 * and does it wherever it likes, and only the ones it needs:
 *
 *   gcc   -O0 : 2, 3, 5 ended up at &f + 48, +56, +64
 *   clang -O0 : the same values lie BELOW &f (clang uses a different frame)
 *   gcc   -O2 : saves only rsi/rdx/rcx, and in a completely different place
 *
 * In other words, you can't pick a constant even within a single compiler.
 * The only "manual" way is to save the incoming registers yourself,
 * into a known location. That's exactly what the prologue of a variadic
 * function generated by the compiler for va_start does.
 *
 * IMPORTANT: even the __asm__ trick below relies on the unwritten agreement
 * that the prologue doesn't touch rdi..r9 before the first statement of the
 * body. In practice that's true (push rbp / mov / sub rsp), but the ABI
 * doesn't promise it — this is a demonstration of the mechanism, not a
 * technique for production code.
 *
 * Build:  gcc -O0 varargs_test_X86_64.c
 *         clang -O2 varargs_test_X86_64.c      (works at any -O level)
 */

#include <stdio.h>
#include <stdint.h>

#if !defined(__x86_64__)
#  error "This file is about the x86-64 System V ABI. Portable version: varargs_test_stdarg.c"
#endif

/* ------------------------------------------------------------------ */
/* 1. How it does NOT work (the original version)                     */
/* ------------------------------------------------------------------ */

/* Naive idea: "arguments go on the stack right after f".
   This reads memory inside the function's frame — it's valid, but
   contains garbage rather than arguments. It prints nonsense, no crash. */
__attribute__((noinline))
void my_printf3_naive(const char *f, ...)
{
    uintptr_t p = (uintptr_t)&f;
    int v1 = *(int *)(p + 8);   /* this isn't actually 2 */
    int v2 = *(int *)(p + 16);  /* this isn't actually 3 */
    int v3 = *(int *)(p + 24);  /* this isn't actually 5 */
    printf("naive    : ");
    printf(f, v1, v2, v3);
}

/* ------------------------------------------------------------------ */
/* 2. How it works: save the argument registers ourselves             */
/* ------------------------------------------------------------------ */

/* The regs[] array is the same thing as the ABI's "register save area",
   except we put it wherever we want. */
__attribute__((noinline))
void my_printf3_manually(const char *f, ...)
{
    uint64_t regs[6];   /* rdi, rsi, rdx, rcx, r8, r9 */

    __asm__ __volatile__(
        "movq %%rdi,  0(%0)\n\t"
        "movq %%rsi,  8(%0)\n\t"
        "movq %%rdx, 16(%0)\n\t"
        "movq %%rcx, 24(%0)\n\t"
        "movq %%r8,  32(%0)\n\t"
        "movq %%r9,  40(%0)\n\t"
        :
        : "r"(regs)
        : "memory");

    /* regs[0] is f itself, followed by the other arguments in order.
       ints occupy the low 32 bits of their 64-bit slots. */
    int v1 = (int)regs[1];
    int v2 = (int)regs[2];
    int v3 = (int)regs[3];

    printf("manual   : ");
    printf(f, v1, v2, v3);
}

/* ------------------------------------------------------------------ */
/* 3. Bonus: what to do with arguments 7, 8, ...                      */
/* ------------------------------------------------------------------ */

/* Arguments beyond the sixth are placed on the stack by the ABI — after the
   return address, i.e. at rbp+16, rbp+24, ... That's a real ABI guarantee,
   not a guess. __builtin_frame_address(0) guarantees that rbp exists
   and returns exactly it. */
__attribute__((noinline))
long my_sum_n_manually(int n, ...)
{
    uint64_t regs[6];

    __asm__ __volatile__(
        "movq %%rdi,  0(%0)\n\t"
        "movq %%rsi,  8(%0)\n\t"
        "movq %%rdx, 16(%0)\n\t"
        "movq %%rcx, 24(%0)\n\t"
        "movq %%r8,  32(%0)\n\t"
        "movq %%r9,  40(%0)\n\t"
        :
        : "r"(regs)
        : "memory");

    long s = 0;
    int i = 0;

    /* n is in rdi (regs[0]), the first five numbers are in regs[1..5] */
    for (; i < n && i < 5; i++)
        s += (int)regs[i + 1];

    /* the rest are on the stack: [rbp+8] return address, [rbp+16] the first one */
    const uint64_t *stack_args = (const uint64_t *)__builtin_frame_address(0) + 2;
    for (; i < n; i++)
        s += (int)stack_args[i - 5];

    return s;
}

/* ------------------------------------------------------------------ */

int main(void)
{
    printf("expected : 2 + 3 = 5!\n");
    my_printf3_naive("%d + %d = %d!\n", 2, 3, 5);
    my_printf3_manually("%d + %d = %d!\n", 2, 3, 5);
    putchar('\n');

    printf("expected : 1+2+3+4+5+6+7+8 = 36\n");
    printf("manual   : 1+2+...+8 = %ld\n", my_sum_n_manually(8, 1, 2, 3, 4, 5, 6, 7, 8));

    return 0;
}
