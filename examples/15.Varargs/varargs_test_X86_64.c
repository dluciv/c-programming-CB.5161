/*
 * Ручной разбор вариативных аргументов на x86-64 (System V ABI).
 *
 * Главное, что нужно понять: "..." НЕ кладёт аргументы на стек.
 * Многоточие меняет только правила проверки типов и умолчательные
 * расширения (char/short -> int, float -> double). Где физически лежат
 * аргументы — решает ABI, а не многоточие.
 *
 * System V AMD64 ABI (Linux, *BSD, macOS):
 *   целые аргументы 1..6  -> rdi, rsi, rdx, rcx, r8, r9
 *   аргументы 7 и далее   -> стек, сразу за адресом возврата (rbp+16, +24, ...)
 *   float/double 1..8     -> xmm0..xmm7 (al = сколько их передано)
 *
 * Поэтому наивная попытка "аргументы лежат сразу за &f" даёт мусор:
 * компилятор сначала прячет пришедшие регистры в свой стековый кадр,
 * и делает это там, где ему удобно, да ещё и только те, что нужны:
 *
 *   gcc   -O0 : 2, 3, 5 оказались по адресам &f + 48, +56, +64
 *   clang -O0 : те же значения лежат НИЖЕ &f (у clang другой кадр)
 *   gcc   -O2 : сохраняет только rsi/rdx/rcx, и совсем в другом месте
 *
 * То есть подобрать константу невозможно даже в пределах одного
 * компилятора. Единственный "ручной" способ — сохранить пришедшие
 * регистры самому, в известное место. Ровно это и делает пролог
 * вариативной функции, который компилятор генерирует под va_start.
 *
 * ВАЖНО: даже трюк с __asm__ ниже держится на негласном соглашении,
 * что пролог не трогает rdi..r9 до первого оператора тела. На практике
 * это так (push rbp / mov / sub rsp), но ABI этого не обещает — это
 * демонстрация механизма, а не приём для боевого кода.
 *
 * Собирать:  gcc -O0 varargs_test_X86_64.c
 *            clang -O2 varargs_test_X86_64.c      (работает при любом -O)
 */

#include <stdio.h>
#include <stdint.h>

#if !defined(__x86_64__)
#  error "Этот файл — про x86-64 System V ABI. Портативная версия: varargs_test_stdarg.c"
#endif

/* ------------------------------------------------------------------ */
/* 1. Как это НЕ работает (первоначальный вариант)                    */
/* ------------------------------------------------------------------ */

/* Наивная идея: "аргументы идут по стеку сразу за f".
   Здесь читается память внутри кадра функции — она валидна, но
   содержит не аргументы, а мусор. Печатается чушь, падения нет. */
__attribute__((noinline))
void my_printf3_naive(const char *f, ...)
{
    uintptr_t p = (uintptr_t)&f;
    int v1 = *(int *)(p + 8);   /* на самом деле это не 2 */
    int v2 = *(int *)(p + 16);  /* на самом деле это не 3 */
    int v3 = *(int *)(p + 24);  /* на самом деле это не 5 */
    printf("naive    : ");
    printf(f, v1, v2, v3);
}

/* ------------------------------------------------------------------ */
/* 2. Как это работает: сами сохраняем регистры аргументов            */
/* ------------------------------------------------------------------ */

/* Массив regs[] — это то же самое, что "register save area" из ABI,
   только мы кладём его туда, куда хотим сами. */
__attribute__((noinline))
void my_printf3_manually(const char *f, ...)
{
    uint64_t regs[6];   /* rdi, rsi, rdx, rcx, r8, r9 */

    __asm__ __volatile__(
        "movq %%rdi,  0(%0)\n\t"
        "movq %%rsi,  8(%0)\n\t"
        "movq %%rdx, 16(%0)\n\t"
        "movq %%rcx, 24(%0)\n\t"
        "movq %%r8,  32(%0)\n\t"
        "movq %%r9,  40(%0)\n\t"
        :
        : "r"(regs)
        : "memory");

    /* regs[0] — это сам f, дальше по порядку остальные аргументы.
       int-ы занимают младшие 32 бита своих 64-битных слотов. */
    int v1 = (int)regs[1];
    int v2 = (int)regs[2];
    int v3 = (int)regs[3];

    printf("manual   : ");
    printf(f, v1, v2, v3);
}

/* ------------------------------------------------------------------ */
/* 3. Бонус: что делать с аргументами 7, 8, ...                       */
/* ------------------------------------------------------------------ */

/* Аргументы сверх шести ABI кладёт на стек — за адресом возврата,
   то есть по адресам rbp+16, rbp+24, ... Это уже настоящая гарантия
   ABI, а не догадка. __builtin_frame_address(0) гарантирует, что
   rbp будет, и возвращает именно его. */
__attribute__((noinline))
long my_sum_n_manually(int n, ...)
{
    uint64_t regs[6];

    __asm__ __volatile__(
        "movq %%rdi,  0(%0)\n\t"
        "movq %%rsi,  8(%0)\n\t"
        "movq %%rdx, 16(%0)\n\t"
        "movq %%rcx, 24(%0)\n\t"
        "movq %%r8,  32(%0)\n\t"
        "movq %%r9,  40(%0)\n\t"
        :
        : "r"(regs)
        : "memory");

    long s = 0;
    int i = 0;

    /* n лежит в rdi (regs[0]), первые пять чисел — в regs[1..5] */
    for (; i < n && i < 5; i++)
        s += (int)regs[i + 1];

    /* остальные — на стеке: [rbp+8] адрес возврата, [rbp+16] первый */
    const uint64_t *stack_args = (const uint64_t *)__builtin_frame_address(0) + 2;
    for (; i < n; i++)
        s += (int)stack_args[i - 5];

    return s;
}

/* ------------------------------------------------------------------ */

int main(void)
{
    printf("expected : 2 + 3 = 5!\n");
    my_printf3_naive("%d + %d = %d!\n", 2, 3, 5);
    my_printf3_manually("%d + %d = %d!\n", 2, 3, 5);
    putchar('\n');

    printf("expected : 1+2+3+4+5+6+7+8 = 36\n");
    printf("manual   : 1+2+...+8 = %ld\n", my_sum_n_manually(8, 1, 2, 3, 4, 5, 6, 7, 8));

    return 0;
}
